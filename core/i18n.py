"""后端文案的双语上下文（T14）。

为什么不用前端词典兜：后端返回的是**用户数据形态的字符串**（预设 note、
下载清单字段、预览头），前端词典按子串替换会误切（踩过的坑：「通用短词条
会误切后端字符串，但解法不是去加长词条盖它」）——正解是后端按请求语言
**直接返回**对应文案。

用法：
    from core.i18n import T, set_lang
    set_lang("en")          # dispatch 每个请求开头按 ?lang= / body.lang 设置
    T("由 MPV Config Builder 生成", "Generated by MPV Config Builder")

线程模型：HTTP 走 ThreadingHTTPServer，语言挂在 threading.local 上；
webui/api.py 的 dispatch() **每个请求必设**（无参 = 回中文），同一线程的
上一个请求不会把语言泄漏给下一个。中文是原文——zh 串同时充当键与兜底，
en 缺失时宁可退回中文也不要留空。
"""
import re
import threading

_local = threading.local()
SUPPORTED = ("zh", "en")


def set_lang(lang):
    """设置当前请求的语言。None / 未知值一律回中文（显式重置，防线程残留）。"""
    _local.lang = lang if lang in SUPPORTED else "zh"


def get_lang():
    return getattr(_local, "lang", "zh")


def T(zh, en):
    """按当前语言取一条文案。两个参数都必须给全——半句翻译不如不翻。"""
    return en if get_lang() == "en" else zh


