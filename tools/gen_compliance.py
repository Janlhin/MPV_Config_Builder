# -*- coding: utf-8 -*-
"""Regenerate docs/compliance/SHA256SUMS from the files that ship with the repo.

Why a script: hand-copied hashes drift. The checksum file is the machine-readable
source; the prose ledger is generated/updated separately and should never be
trusted over this output.

Usage:
    python tools/gen_compliance.py
"""
from pathlib import Path
import hashlib

ROOT = Path(__file__).resolve().parent.parent

# Files that are distributed with the repository and must be traceable.
# Add a file here only when it is part of the shipped artifact, not a dev-only
# document.
FILES = (
    "LICENSE",
    "docs/compliance/NOTICE.txt",
    "data/mpv_options_zh.json",
    "data/mpv_keybindings.json",
    "data/mpv_commands.json",
    "data/_mpv_options_raw.txt",
)


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for chunk in iter(lambda: f.read(1024 * 1024), b""):
            h.update(chunk)
    return h.hexdigest()


def main() -> int:
    lines = ["# Generated by tools/gen_compliance.py; do not edit by hand."]
    for rel in FILES:
        path = ROOT / rel
        if not path.is_file():
            print(f"missing: {rel}")
            return 1
        lines.append(f"{sha256(path)}  {rel}  # {path.stat().st_size} bytes")
    out = ROOT / "docs" / "compliance" / "SHA256SUMS"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {out.relative_to(ROOT)} ({len(FILES)} files)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
